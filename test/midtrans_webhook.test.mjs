import { handleMidtrans } from '../supabase/functions/midtrans-webhook/handler.mjs';
import assert from 'node:assert/strict';
const body={order_id:'dummy',status_code:'200',gross_amount:'50000.00',transaction_status:'settlement'};
const key='dummy-test-secret';
const signature=Array.from(new Uint8Array(await crypto.subtle.digest('SHA-512',new TextEncoder().encode(body.order_id+body.status_code+body.gross_amount+key))),b=>b.toString(16).padStart(2,'0')).join('');
const request=b=>new Request('https://local.invalid',{method:'POST',body:JSON.stringify(b)});
let writes=0;
const services={serverKey:key,process:async()=>{writes++;return {success:true};}};
assert.equal((await handleMidtrans(request(body),services)).status,403);
assert.equal((await handleMidtrans(request({...body,signature_key:'0'.repeat(128)}),services)).status,403);
assert.equal((await handleMidtrans(request({...body,signature_key:signature}),{...services,serverKey:''})).status,503);
assert.equal(writes,0);
assert.equal((await handleMidtrans(request({...body,signature_key:signature}),services)).status,200);
assert.equal(writes,1);
assert.equal((await handleMidtrans(request({...body,signature_key:signature,gross_amount:'999999.00'}),services)).status,403);
assert.equal(writes,1);
const failed=await handleMidtrans(request({...body,signature_key:signature}),{...services,process:async()=>({success:false,error:'PRIVATE_DATABASE_ERROR'})});
assert.equal(failed.status,503); assert.ok(!(await failed.text()).includes('PRIVATE_DATABASE_ERROR'));
console.log('PASS webhook: mandatory signature/config, valid payment accepted, tampered amount rejected, database failure retryable/sanitized');
